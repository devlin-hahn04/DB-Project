BEGIN;

-- Ensure required fields cannot be NULL
ALTER TABLE driver
    ALTER COLUMN first_name SET NOT NULL,
    ALTER COLUMN last_name SET NOT NULL,
    ALTER COLUMN license_number SET NOT NULL,
    ALTER COLUMN hired_at SET NOT NULL;

-- Ensure license numbers are unique
ALTER TABLE driver
    ADD CONSTRAINT driver_license_number_key
    UNIQUE (license_number);

-- Automatically generate driver IDs
ALTER TABLE driver
    ALTER COLUMN driver_id
    ADD GENERATED BY DEFAULT AS IDENTITY;

-- Synchronize generated IDs with existing drivers (1–12)
SELECT setval(
    pg_get_serial_sequence('public.driver', 'driver_id'),
    COALESCE((SELECT MAX(driver_id) FROM driver), 1),
    EXISTS (SELECT 1 FROM driver)
);

COMMIT;