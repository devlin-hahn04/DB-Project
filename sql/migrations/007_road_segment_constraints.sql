BEGIN;

-- Required values for the Road Segment REST API.
ALTER TABLE public.road_segment
    ALTER COLUMN name SET NOT NULL,
    ALTER COLUMN geom SET NOT NULL;

-- Create a new ID for each inserted road segment.
ALTER TABLE public.road_segment
    ALTER COLUMN road_id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Advance the new sequence beyond the existing Phase 1 IDs.
SELECT setval(
    pg_get_serial_sequence('public.road_segment', 'road_id'),
    COALESCE((SELECT MAX(road_id) FROM public.road_segment), 1),
    EXISTS (SELECT 1 FROM public.road_segment)
);

-- Supply a timestamp automatically when creating a road segment.
ALTER TABLE public.road_segment
    ALTER COLUMN created_at SET DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC');

-- Enforce basic value and geometry integrity.
ALTER TABLE public.road_segment
    ADD CONSTRAINT road_segment_name_nonempty CHECK (length(btrim(name)) > 0),
    ADD CONSTRAINT road_segment_speed_nonnegative CHECK (speed_limit_kph IS NULL OR speed_limit_kph >= 0),
    ADD CONSTRAINT road_segment_direction_valid CHECK (direction IS NULL OR direction IN ('both', 'forward')),
    ADD CONSTRAINT road_segment_geom_valid CHECK (ST_IsValid(geom));

COMMIT;
