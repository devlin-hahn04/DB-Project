BEGIN;

-- Required values for the Parking Area REST API.
ALTER TABLE public.parking_area
    ALTER COLUMN name SET NOT NULL,
    ALTER COLUMN geom SET NOT NULL;

-- Create a new ID for each inserted parking area.
ALTER TABLE public.parking_area
    ALTER COLUMN parking_area_id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Advance the new sequence beyond the existing Phase 1 IDs.
SELECT setval(
    pg_get_serial_sequence('public.parking_area', 'parking_area_id'),
    COALESCE((SELECT MAX(parking_area_id) FROM public.parking_area), 1),
    EXISTS (SELECT 1 FROM public.parking_area)
);

-- Supply a timestamp automatically when creating a parking area.
ALTER TABLE public.parking_area
    ALTER COLUMN created_at SET DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC');

-- Enforce basic value and geometry integrity.
ALTER TABLE public.parking_area
    ADD CONSTRAINT parking_area_name_nonempty CHECK (length(btrim(name)) > 0),
    ADD CONSTRAINT parking_area_capacity_nonnegative CHECK (capacity IS NULL OR capacity >= 0),
    ADD CONSTRAINT parking_area_geom_valid CHECK (ST_IsValid(geom));

COMMIT;