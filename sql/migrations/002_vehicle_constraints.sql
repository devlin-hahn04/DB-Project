BEGIN;

-- Require existing vehicle types and statuses.
ALTER TABLE public.vehicle
    ALTER COLUMN vehicle_type_id SET NOT NULL,
    ALTER COLUMN vehicle_status_id SET NOT NULL,
    ALTER COLUMN plate_number SET NOT NULL;

-- Prevent duplicate vehicle plate numbers.
ALTER TABLE public.vehicle
    ADD CONSTRAINT vehicle_plate_number_unique UNIQUE (plate_number);

-- Generate vehicle IDs automatically for new records.
ALTER TABLE public.vehicle
    ALTER COLUMN vehicle_id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Synchronize the identity sequence with existing Phase 1 records.
SELECT setval(
    pg_get_serial_sequence('public.vehicle', 'vehicle_id'),
    COALESCE((SELECT MAX(vehicle_id) FROM public.vehicle), 1),
    EXISTS (SELECT 1 FROM public.vehicle)
);

-- Automatically timestamp new vehicles if the API does not supply created_at.
ALTER TABLE public.vehicle
    ALTER COLUMN created_at SET DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC');

COMMIT;
