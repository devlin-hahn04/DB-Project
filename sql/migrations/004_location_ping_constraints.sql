BEGIN;

-- Require a vehicle, timestamp and point for every ping.
ALTER TABLE public.location_ping
    ALTER COLUMN vehicle_id SET NOT NULL,
    ALTER COLUMN ts SET NOT NULL,
    ALTER COLUMN geom SET NOT NULL;

-- Generate IDs automatically for new pings.
ALTER TABLE public.location_ping
    ALTER COLUMN ping_id
    ADD GENERATED BY DEFAULT AS IDENTITY;

-- Synchronize the sequence with existing records.
SELECT setval(
    pg_get_serial_sequence('public.location_ping', 'ping_id'),
    COALESCE((SELECT MAX(ping_id) FROM public.location_ping), 1),
    EXISTS (SELECT 1 FROM public.location_ping)
);

-- Speed up vehicle history and time-range filters.
CREATE INDEX IF NOT EXISTS idx_location_ping_vehicle_ts
    ON public.location_ping (vehicle_id, ts);

COMMIT;
