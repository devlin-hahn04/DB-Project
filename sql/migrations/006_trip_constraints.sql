BEGIN;

-- Required fields for every trip (validated against existing data first).
ALTER TABLE public.trip
    ALTER COLUMN vehicle_id SET NOT NULL,
    ALTER COLUMN start_ts SET NOT NULL,
    ALTER COLUMN end_ts SET NOT NULL;

-- Preserve the existing ETL-assigned IDs and generate IDs for new trips.
ALTER TABLE public.trip
    ALTER COLUMN trip_id ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(
    pg_get_serial_sequence('public.trip', 'trip_id'),
    COALESCE((SELECT MAX(trip_id) FROM public.trip), 1),
    EXISTS (SELECT 1 FROM public.trip)
);

ALTER TABLE public.trip
    ADD CONSTRAINT trip_time_interval_valid CHECK (end_ts > start_ts),
    ADD CONSTRAINT trip_distance_nonnegative CHECK (
        distance_km IS NULL OR (distance_km >= 0 AND distance_km <> 'NaN'::float8)
    );

CREATE INDEX IF NOT EXISTS idx_trip_vehicle_start_ts
    ON public.trip (vehicle_id, start_ts);

COMMIT;