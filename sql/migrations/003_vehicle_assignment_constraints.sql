BEGIN;

-- Require valid vehicle and driver references.
ALTER TABLE public.vehicle_assignment
    ALTER COLUMN vehicle_id SET NOT NULL,
    ALTER COLUMN driver_id SET NOT NULL,
    ALTER COLUMN assigned_from SET NOT NULL;

-- Generate IDs automatically for new assignments.
ALTER TABLE public.vehicle_assignment
    ALTER COLUMN assignment_id
    ADD GENERATED BY DEFAULT AS IDENTITY;

-- Synchronize the sequence with existing records.
SELECT setval(
    pg_get_serial_sequence(
        'public.vehicle_assignment',
        'assignment_id'
    ),
    COALESCE(
        (SELECT MAX(assignment_id)
         FROM public.vehicle_assignment),
        1
    ),
    EXISTS (
        SELECT 1
        FROM public.vehicle_assignment
    )
);

COMMIT;